const dataFixtureT = farmNow - 3600 // the feed is one hour old

var dataFixture = fmt.Sprintf(`-- Generated by scripts/build_data.py. Lowest buyout per unit, in copper: itemID, price, quantity listed.
local _, ns = ...
ns.seed = { t = %d, label = "EU PvP Alliance", faction = "Alliance", n = 4, flat = { 7,700,70,8,800,80,9,900,90,10,1000,100 } }
`, dataFixtureT)

func feedGame(t *testing.T, data string) string {
	t.Helper()
	game := farmGame(t, farmDataFixture, "")
	if data != "" {
		if err := os.WriteFile(filepath.Join(game, "Interface", "AddOns", "AHProfit", "Data.lua"), []byte(data), 0644); err != nil {
			t.Fatal(err)
		}
	}
	return game
}

// The page follows AH Profit's lookup, feed included.
func TestFarmFeedFollowsTheGamesOrder(t *testing.T) {
	ref := loadFarmRef(feedGame(t, dataFixture), nil)
	if ref.Seed == nil || ref.Seed.Faction != "Alliance" || ref.Seed.Prices[8] != [2]int{800, 80} || !ref.Seed.Time.Equal(time.Unix(dataFixtureT, 0)) {
		t.Fatalf("seed %+v", ref.Seed)
	}
	now := time.Unix(farmNow, 0)
	elf := []CharView{{Name: "Elf", Realm: "R", Faction: "Alliance", Updated: now}, {Name: "Orc", Realm: "R", Faction: "Horde"}}
	build := func(liveFull, sharedFull int64, own, guild string) FarmView {
		sv := fmt.Sprintf(`AHProfitDB={v=2,live={["R|Alliance"]={%s,full=%d},["R|Horde"]={p={},q={},t={},full=0}},shared={["R|Alliance"]={%s,full=%d,from={}}},bank={["Elf-R"]={t=1,items={{7,1,0},{8,1,0},{9,1,0},{10,1,0},{11,1,0}}},["Orc-R"]={t=1,items={{7,1,0}}}}}`,
			own, liveFull, guild, sharedFull)
		fv, err := buildFarm([]byte(sv), elf, now, ref)
		if err != nil {
			t.Fatal(err)
		}
		return fv
	}
	src := func(fv FarmView, char string, id int) string {
		r := farmRow(fv, char, id)
		return fmt.Sprintf("%d %s", r.Price, r.Source)
	}
	// own: 7 fresh (30 min), 8 older than the feed (3 h), 9 older than 2 h but newer than the feed? (no: feed is 1 h old) -> 9 at 50 min is fresh
	// guild: 10 newer than the feed (20 min), 8 older than the feed (2 h)
	own := fmt.Sprintf(`p={[7]=71,[8]=81},q={[7]=1,[8]=1},t={[7]=%d,[8]=%d}`, farmNow-1800, farmNow-3*3600)
	guild := fmt.Sprintf(`p={[10]=101,[8]=82},q={[10]=1,[8]=1},t={[10]=%d,[8]=%d}`, farmNow-1200, farmNow-2*3600)
	fv := build(0, 0, own, guild)
	for id, want := range map[int]string{7: "71 scan", 8: "800 feed", 9: "900 feed", 10: "101 guild", 11: "0 "} {
		if got := src(fv, "Elf-R", id); got != want {
			t.Fatalf("item %d: %q, want %q", id, got, want)
		}
	}
	if got := src(fv, "Orc-R", 7); got != "0 " {
		t.Fatalf("an Alliance feed is not used for a Horde house: %q", got)
	}
	// a complete own scan newer than the feed: the feed is not used, older own prices are
	fv = build(farmNow-600, 0, own, guild)
	for id, want := range map[int]string{8: "82 guild", 9: "0 ", 7: "71 scan"} {
		if got := src(fv, "Elf-R", id); got != want {
			t.Fatalf("own full scan newer than feed, item %d: %q, want %q", id, got, want)
		}
	}
	// a complete guild scan newer than the feed hides it too, unless it is outside the 12 h / +300 s bounds
	fv = build(0, farmNow-600, own, guild)
	if got := src(fv, "Elf-R", 9); got != "0 " {
		t.Fatalf("guild full scan newer than feed: %q", got)
	}
	fv = build(0, farmNow+10*86400, own, guild)
	if got := src(fv, "Elf-R", 9); got != "900 feed" {
		t.Fatalf("a guild full scan far ahead does not hide the feed: %q", got)
	}
	// the render names the source
	html, _ := renderFarmBody(View{Farm: build(0, 0, own, guild)})
	if !strings.Contains(html, "AH Profit&#39;s bundled prices") && !strings.Contains(html, "AH Profit's bundled prices") {
		t.Fatal("feed rows say where the price comes from")
	}
	// without Data.lua there is no feed
	if ref := loadFarmRef(feedGame(t, ""), nil); ref.Seed != nil {
		t.Fatal("no Data.lua, no feed")
	}
}

func TestFarmFeedMalformedMeansNoFeed(t *testing.T) {
	for name, body := range map[string]string{
		"odd length":    strings.Replace(dataFixture, "10,1000,100 }", "10,1000 }", 1),
		"zero price":    strings.Replace(dataFixture, "8,800,80", "8,0,80", 1),
		"string id":     strings.Replace(dataFixture, "8,800,80", `"8",800,80`, 1),
		"bad faction":   strings.Replace(dataFixture, `faction = "Alliance"`, `faction = "Both"`, 1),
		"no time":       strings.Replace(dataFixture, fmt.Sprintf("t = %d,", dataFixtureT), "", 1),
		"code":          "ns.seed = loadstring('x')()",
		"cut off":       dataFixture[:len(dataFixture)/2],
		"too many vals": "ns.seed = { t = 1, flat = {" + strings.Repeat("1,1,1,", 200000) + "} }",
	} {
		if ref := loadFarmRef(feedGame(t, body), nil); ref.Seed != nil {
			t.Fatalf("%s: a malformed feed is not used: %+v", name, ref.Seed)
		}
	}
	// no faction field: used for both factions, as the addon does
	noFaction := strings.Replace(dataFixture, `faction = "Alliance", `, "", 1)
	if ref := loadFarmRef(feedGame(t, noFaction), nil); ref.Seed == nil || ref.Seed.Faction != "" {
		t.Fatal("a feed without a faction is used for any house")
	}
}

// S4: an unchanged AHProfit.lua is not read or parsed again; a changed one,
// or another account's, is.
func TestFarmUnchangedSaveNotReparsed(t *testing.T) {
	accountConfigEnv(t)
	game := t.TempDir()
	accountSave(t, game, "A#1", "Alpha")
	accountSave(t, game, "B#1", "Beta")
	f := farmWrite(t, game, "A#1", farmFixture())
	farmWrite(t, game, "B#1", strings.Replace(farmFixture(), `["cut"] = 5`, `["cut"] = 15`, 1))
	a, b := accountApp(t, game)
	if err := a.selectAccount("A#1"); err != nil {
		t.Fatal(err)
	}
	accountProjection(t, b)
	parses := farmParses
	for i := 0; i < 3; i++ {
		accountProjection(t, b)
	}
	if farmParses != parses {
		t.Fatalf("unchanged file parsed %d more times", farmParses-parses)
	}
	if a.snapshot().Farm.Error != "" || !a.snapshot().Farm.Present {
		t.Fatal("the page still has its data")
	}
	// rewritten with a new time: parsed again
	later := time.Now().Add(time.Minute)
	if err := os.WriteFile(f, []byte(strings.Replace(farmFixture(), `["cut"] = 5`, `["cut"] = 15`, 1)), 0644); err != nil {
		t.Fatal(err)
	}
	os.Chtimes(f, later, later)
	accountProjection(t, b)
	if farmParses != parses+1 || a.snapshot().Farm.Cut != 15 {
		t.Fatalf("a changed file is parsed again: %d, cut %d", farmParses-parses, a.snapshot().Farm.Cut)
	}
	// a broken write is not cached: the next refresh tries again
	os.WriteFile(f, []byte("AHProfitDB = {"), 0644)
	os.Chtimes(f, later.Add(time.Minute), later.Add(time.Minute))
	accountProjection(t, b)
	accountProjection(t, b)
	if farmParses != parses+3 {
		t.Fatalf("a file that failed to parse is retried: %d", farmParses-parses)
	}
	// another account with a file of the same size and time is parsed, not reused
	os.WriteFile(f, []byte(farmFixture()), 0644)
	st, _ := os.Stat(f)
	fb := filepath.Join(game, "WTF", "Account", "B#1", "SavedVariables", "AHProfit.lua")
	os.Chtimes(fb, st.ModTime(), st.ModTime())
	accountProjection(t, b)
	before := farmParses
	if err := a.selectAccount("B#1"); err != nil {
		t.Fatal(err)
	}
	accountProjection(t, b)
	if farmParses == before || a.snapshot().Farm.Cut != 15 {
		t.Fatalf("another account's file is parsed: cut %d", a.snapshot().Farm.Cut)
	}
}

// S4: a file over the cap is refused before it is read into memory.
func TestFarmOversizedFileNotRead(t *testing.T) {
	accountConfigEnv(t)
	game := t.TempDir()
	accountSave(t, game, "A#1", "Alpha")
	farmWrite(t, game, "A#1", farmFixture())
	a, _ := accountApp(t, game)
	old := ahpMaxBytes
	t.Cleanup(func() { ahpMaxBytes = old })
	ahpMaxBytes = 100
	a.mu.Lock()
	data, _, key, err := a.readAHProfitLocked("")
	a.mu.Unlock()
	if err == nil || len(data) != 0 || key == "" {
		t.Fatalf("over the cap: not read (%d bytes, %v)", len(data), err)
	}
}
